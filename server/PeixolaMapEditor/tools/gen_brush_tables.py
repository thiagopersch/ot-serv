"""Converts RME's source/brush_tables.cpp into Rust lookup tables (pme-core/src/brush_tables.rs)."""
import re, sys

src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
enums = {
    "BORDER_NONE": 0, "NORTH_HORIZONTAL": 1, "EAST_HORIZONTAL": 2, "SOUTH_HORIZONTAL": 3, "WEST_HORIZONTAL": 4,
    "NORTHWEST_CORNER": 5, "NORTHEAST_CORNER": 6, "SOUTHWEST_CORNER": 7, "SOUTHEAST_CORNER": 8,
    "NORTHWEST_DIAGONAL": 9, "NORTHEAST_DIAGONAL": 10, "SOUTHEAST_DIAGONAL": 11, "SOUTHWEST_DIAGONAL": 12,
    "CARPET_CENTER": 13,
    "WALL_POLE": 0, "WALL_SOUTH_END": 1, "WALL_EAST_END": 2, "WALL_NORTHWEST_DIAGONAL": 3, "WALL_WEST_END": 4,
    "WALL_NORTHEAST_DIAGONAL": 5, "WALL_HORIZONTAL": 6, "WALL_SOUTH_T": 7, "WALL_NORTH_END": 8, "WALL_VERTICAL": 9,
    "WALL_SOUTHWEST_DIAGONAL": 10, "WALL_EAST_T": 11, "WALL_SOUTHEAST_DIAGONAL": 12, "WALL_WEST_T": 13,
    "WALL_NORTH_T": 14, "WALL_INTERSECTION": 15, "WALL_UNTOUCHABLE": 16,
    "TABLE_NORTH_END": 0, "TABLE_SOUTH_END": 1, "TABLE_EAST_END": 2, "TABLE_WEST_END": 3,
    "TABLE_HORIZONTAL": 4, "TABLE_VERTICAL": 5, "TABLE_ALONE": 6,
    "TILE_NORTHWEST": 1, "TILE_NORTH": 2, "TILE_NORTHEAST": 4, "TILE_WEST": 8, "TILE_EAST": 16,
    "TILE_SOUTHWEST": 32, "TILE_SOUTH": 64, "TILE_SOUTHEAST": 128,
    "WALLTILE_NORTH": 1, "WALLTILE_WEST": 2, "WALLTILE_EAST": 4, "WALLTILE_SOUTH": 8,
}

def ev(expr):
    expr = re.sub(r"//[^\n]*", "", expr)
    expr = re.sub(r"[A-Z_]+", lambda m: str(enums[m.group(0)]), expr)
    return eval(expr)

tables = {"border_types": [0] * 256, "full_border_types": [0] * 16, "half_border_types": [0] * 16,
          "table_types": [0] * 256, "carpet_types": [0] * 256}
pat = re.compile(r"\w+::(\w+)\[([^\]]*)\][^=]*=([^;]*);", re.S)
count = 0
for m in pat.finditer(src):
    name, idx, val = m.group(1), m.group(2), m.group(3)
    tables[name][ev(idx)] = ev(val)
    count += 1

out = ["// @generated by tools/gen_brush_tables.py from RME source/brush_tables.cpp. Do not edit.", ""]
for name, vals in tables.items():
    out.append(f"pub static {name.upper()}: [u32; {len(vals)}] = [")
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(f"0x{v:08X}" for v in vals[i:i + 8]) + ",")
    out.append("];")
    out.append("")
open(sys.argv[2], "w", newline="\n").write("\n".join(out))
print("assignments:", count)
