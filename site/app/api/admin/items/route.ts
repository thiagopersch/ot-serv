export const GET = withAudit(async function GET(request: Request) {
  const { response } = await requireAdminSession();
  if (response) return response;

  const url = new URL(request.url);

  const ids = parseIdsParam(url);
  if (ids) {
    const itemsById = await prisma.item.findMany({ where: { id: { in: ids } }, select: ITEM_LIST_SELECT });
    return NextResponse.json(buildPaginatedResult(itemsById, itemsById.length, 1, itemsById.length || 1));
  }

  const { page, pageSize, search } = parsePaginationParams(url);
  const type = url.searchParams.get("type");
  const weaponType = url.searchParams.get("weaponType");
  const slotType = url.searchParams.get("slotType");
  const published = url.searchParams.get("published");
  const idMin = url.searchParams.get("idMin");
  const idMax = url.searchParams.get("idMax");
  const hasImage = await hasImageIdFilter("item", url.searchParams.get("hasImage"));

  const where: Prisma.ItemWhereInput = {
    ...(search
      ? {
          OR: [
            { name: { contains: search } },
            ...(Number.isFinite(Number(search))
              ? [{ id: Number(search) }]
              : []),
          ],
        }
      : {}),
    ...(type ? { type } : {}),
    ...(weaponType ? { weaponType } : {}),
    ...(slotType ? { slotType } : {}),
    ...(published ? { published: published === "true" } : {}),
    ...(idMin || idMax
      ? {
          id: {
            ...(idMin ? { gte: Number(idMin) } : {}),
            ...(idMax ? { lte: Number(idMax) } : {}),
          },
        }
      : {}),
    // "Possui imagem" considera a imagem custom (`EntityImage`) e a sprite vinculada (`lookTypeId`).
    // Em `AND` para não colidir com o `OR` da busca por nome/id.
    ...(hasImage
      ? {
          AND: [
            "in" in hasImage
              ? { OR: [{ id: hasImage }, { lookTypeId: { not: null } }] }
              : { id: hasImage, lookTypeId: null },
          ],
        }
      : {}),
  };

  const skipCount = shouldSkipCount(url);

  const [items, total] = await Promise.all([
    prisma.item.findMany({
      where,
      orderBy: { id: "asc" },
      select: ITEM_LIST_SELECT,
      skip: (page - 1) * pageSize,
      take: pageSize,
    }),
    skipCount ? Promise.resolve(-1) : prisma.item.count({ where }),
  ]);

  return NextResponse.json(buildPaginatedResult(items, skipCount ? items.length : total, page, pageSize));
});

export const POST = withAudit(async function POST(request: Request) {
  const { session, response } = await requireAdminSession();
  if (response) return response;

  const body = await request.json();
  const parsed = itemSchema.safeParse(body);

  if (!parsed.success) {
    return NextResponse.json(
      { error: parsed.error.issues[0]?.message ?? "Dados inválidos." },
      { status: 422 },
    );
  }

  const existing = await prisma.item.findUnique({
    where: { id: parsed.data.id },
  });
  if (existing) {
    // Id já cadastrado: configuração idêntica é só pulada (nada a gravar); divergente devolve o
    // cadastro atual pro client mostrar a comparação e deixar o admin decidir se substitui (PATCH).
    const existingInput = itemRowToFormInput(existing);
    if (isSameItemConfig(existingInput, parsed.data)) {
      return NextResponse.json({ skipped: true, item: existingInput });
    }
    return NextResponse.json(
      { error: "Já existe um item com esse id.", conflict: true, existing: existingInput },
      { status: 409 },
    );
  }

  const item = await prisma.item.create({ data: itemFormToRow(parsed.data) });
  await syncAutoGeneratedEquipMovements(prisma, item.id, item.slotType);

  await logAudit({
    accountId: Number(session.user.id),
    action: "create",
    entity: "item",
    entityId: item.id,
    metadata: { name: item.name },
  });

  return NextResponse.json({ item: itemRowToFormInput(item) }, { status: 201 });
});
