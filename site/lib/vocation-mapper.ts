import type { Vocation } from "@/lib/generated/prisma/client";
import type { VocationInput } from "@/lib/validations/admin/vocation";

export function vocationToInput(vocation: Vocation): VocationInput {
  return {
    id: vocation.id,
    name: vocation.name,
    description: vocation.description,
    needpremium: vocation.needpremium,
    published: vocation.published,
    publishedGameplay: vocation.publishedGameplay,
    gaincap: vocation.gaincap,
    gainhp: vocation.gainhp,
    gainmana: vocation.gainmana,
    gainhpticks: vocation.gainhpticks,
    gainhpamount: vocation.gainhpamount,
    gainmanaticks: vocation.gainmanaticks,
    gainmanaamount: vocation.gainmanaamount,
    manamultiplier: vocation.manamultiplier,
    attackspeed: vocation.attackspeed,
    soulmax: vocation.soulmax,
    gainsoulticks: vocation.gainsoulticks,
    fromvoc: vocation.fromvoc,
    typeUniverseId: vocation.typeUniverseId,
    lookTypeId: vocation.lookTypeId,
    maxRank: vocation.maxRank,
    archetypeId: vocation.archetypeId,
    specificFragmentItemId: vocation.specificFragmentItemId,
    formula: {
      meleeDamage: vocation.formulaMeleeDamage,
      distDamage: vocation.formulaDistDamage,
      wandDamage: vocation.formulaWandDamage,
      magDamage: vocation.formulaMagDamage,
      magHealingDamage: vocation.formulaMagHealingDamage,
      defense: vocation.formulaDefense,
      magDefense: vocation.formulaMagDefense,
      armor: vocation.formulaArmor,
    },
    skill: {
      fist: vocation.skillFist,
      club: vocation.skillClub,
      sword: vocation.skillSword,
      axe: vocation.skillAxe,
      distance: vocation.skillDistance,
      shielding: vocation.skillShielding,
      fishing: vocation.skillFishing,
      experience: vocation.skillExperience,
    },
  };
}

